const LOCAL_HOSTS = new Set(["localhost", "127.0.0.1", "::1"]);

/** TLS settings for a Postgres URL: none for local, verified for anything remote. */
export function sslFor(databaseUrl: string): ConnectionOptions | undefined {
  const { hostname } = new URL(databaseUrl);
  if (LOCAL_HOSTS.has(hostname)) return undefined;
  if (hostname.endsWith(".supabase.com") || hostname.endsWith(".supabase.co")) {
    return { ca: SUPABASE_ROOT_2021_CA, rejectUnauthorized: true };
  }
  // Other managed hosts (Neon, RDS...) use publicly trusted certificates.
  return { rejectUnauthorized: true };
}
